/// Seeded value-transition traces for checking a formal model of spec §6.2,
/// §6.4, §6.5, §8.1 phase 3 and §8.2 against the real block validator.
///
/// Each seed grows one child chain (`Nexus/Child`). Every case is a block on
/// the chain's current tip, decided by `Block.validateNexus` — the full
/// non-genesis validation path, which runs the fee rule and coinbase
/// (`Block.coinbaseCredit`), the parent-receipt check (`validateWithdrawals`)
/// and the state transition (`LatticeState.proveAndUpdateStateMeasuringGrowth`)
/// — and its post-state is read back from the state the validator returns.
/// An accepted block becomes the next case's tip; a rejected one does not.
///
/// What the model abstracts is made to pass: every address that must sign
/// does, one sponsor signs first and carries the account nonce, amounts are
/// small, blocks are non-genesis, and there are no key-value actions or
/// policies. A rejected case is generated by adding actions to a valid block
/// that breaks exactly one value rule, and that valid block is validated
/// first as the control, so the rejection is the rule's.
///
/// The test also replays each case through a direct transcription of the
/// model (`ModelMirror`) and fails on any disagreement with the validator,
/// both on the verdict and on the post-state.
///
/// Set `LATTICE_VALUE_TRACE_DIR` to write `value-<seed>.json` for seeds
/// 1...`LATTICE_VALUE_TRACE_COUNT` (default 30).
@MainActor
final class ValueTransitionTraceExportTests: XCTestCase {
    func testValueTracesCoverEveryRule() async throws {
        let environment = ProcessInfo.processInfo.environment
        let count = environment["LATTICE_VALUE_TRACE_COUNT"].flatMap(UInt64.init) ?? 30
        let directory = environment["LATTICE_VALUE_TRACE_DIR"].map { URL(fileURLWithPath: $0) }
        if let directory {
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        }
        var coverage: [String: Int] = [:]
        for seed in 1...max(count, 1) {
            let trace = try await ValueTrace.make(seed: seed)
            try await trace.run()
            coverage.merge(trace.coverage, uniquingKeysWith: +)
            if let directory {
                try trace.json().write(to: directory.appendingPathComponent("value-\(seed).json"))
            }
        }
        print("value traces: \(coverage.sorted { $0.key < $1.key })")
        for kind in Violation.allCases {
            XCTAssertGreaterThan(coverage[kind.rawValue] ?? 0, 0, "no case violates \(kind.rawValue)")
        }
        for feature in ["valid:recipient", "valid:burn", "valid:spentMarker", "valid:netting",
                        "valid:nettedOverspend", "valid:zeroDeleted", "valid:withdrawal",
                        "valid:receipt", "valid:deposit", "valid:nettingDebitFirst",
                        "valid:nettingDebitFirstTwoTx", "valid:nettingCoinbase"] {
            XCTAssertGreaterThan(coverage[feature] ?? 0, 0, "no case shows \(feature)")
        }
    }

    func testValueTraceIsDeterministic() async throws {
        let first = try await ValueTrace.make(seed: 1)
        try await first.run()
        let second = try await ValueTrace.make(seed: 1)
        try await second.run()
        XCTAssertEqual(try first.json(), try second.json())
    }
}

// MARK: - Model-level values

private enum Violation: String, CaseIterable {
    case overdraft, feeRule, deltaZero, depositExists, depositZero
    case withdrawWrongAmount, withdrawNoReceipt, withdrawWrongWithdrawer, withdrawSpent
    case receiptExists
    /// Action-shape rules (`TransactionBody+Validity.swift`), checked before
    /// any state is read. The model has no `amountDemanded != 0` rule for a
    /// receipt; a zero-demand or zero-amount withdrawal it rejects through
    /// the deposit rules instead (`implied`).
    case receiptZeroDemand, withdrawZeroDemand, withdrawZeroAmount

    /// The model-level rules a case of this kind breaks as a consequence.
    var implied: Set<Violation> {
        switch self {
        case .withdrawZeroDemand: return [.withdrawWrongAmount, .withdrawNoReceipt]
        case .withdrawZeroAmount: return [.withdrawWrongAmount]
        default: return []
        }
    }

    var isShapeRule: Bool { [.receiptZeroDemand, .withdrawZeroDemand, .withdrawZeroAmount].contains(self) }

    /// Whether `violations` is this kind and only what it implies.
    func labels(_ violations: Set<Violation>) -> Bool {
        violations.contains(self) && violations.subtracting([self]).isSubset(of: implied)
    }
}

private struct DKey: Hashable, Comparable {
    let demander: String
    let amountDemanded: UInt64
    let nonce: UInt64
    var description: String { DepositKey(nonce: UInt128(nonce), demander: demander, amountDemanded: amountDemanded).description }
    static func < (a: DKey, b: DKey) -> Bool { a.description < b.description }
}

private struct RKey: Hashable, Comparable {
    let directory: String
    let demander: String
    let amountDemanded: UInt64
    let nonce: UInt64
    var deposit: DKey { DKey(demander: demander, amountDemanded: amountDemanded, nonce: nonce) }
    var action: ReceiptAction {
        ReceiptAction(withdrawer: "", nonce: UInt128(nonce), demander: demander,
                      amountDemanded: amountDemanded, directory: directory)
    }
    var storageKey: String { ReceiptKey(receiptAction: action).storageKey }
    var description: String { ReceiptKey(receiptAction: action).description }
    static func < (a: RKey, b: RKey) -> Bool { a.description < b.description }
}

private enum VAction {
    case account(owner: String, delta: Int64)
    case deposit(nonce: UInt64, demander: String, amountDemanded: UInt64, amountDeposited: UInt64)
    case withdrawal(withdrawer: String, nonce: UInt64, demander: String, amountDemanded: UInt64, amountWithdrawn: UInt64)
    case receipt(withdrawer: String, nonce: UInt64, demander: String, amountDemanded: UInt64, directory: String)
}

private struct VState: Equatable {
    var balances: [String: UInt64] = [:]
    var deposits: [DKey: UInt64] = [:]
    var receipts: [RKey: String] = [:]
}

// MARK: - The model, transcribed (LatticeProofs/Model.lean `applyBlock`)

private enum ModelMirror {
    /// Every value rule the block breaks (the model stops at the first; this
    /// lists all, so a case can be held to exactly one), and the post-state
    /// when it breaks none.
    static func apply(dir: String, parent: [RKey: String], state: VState, actions: [VAction],
                      reward: UInt64, recipient: String?) -> (violations: Set<Violation>, post: VState?) {
        var violations = Set<Violation>()
        var deltas: [(String, Int64)] = []
        var credits: Int64 = 0, debits: Int64 = 0, deposited: Int64 = 0, withdrawn: Int64 = 0
        for action in actions {
            switch action {
            case let .account(owner, delta):
                if delta == 0 { violations.insert(.deltaZero) }
                if delta > 0 { credits += delta } else { debits -= delta }
                deltas.append((owner, delta))
            case let .receipt(w, _, dm, amount, _):
                credits += Int64(amount); debits += Int64(amount)
                deltas.append((w, -Int64(amount))); deltas.append((dm, Int64(amount)))
            case let .deposit(_, _, _, amount): deposited += Int64(amount)
            case let .withdrawal(_, _, _, _, amount): withdrawn += Int64(amount)
            }
        }
        if credits + deposited > debits + withdrawn { violations.insert(.feeRule) }
        var deposits = state.deposits
        for case let .withdrawal(w, n, dm, amtD, amtW) in actions {
            if amtD == 0 { violations.insert(.withdrawZeroDemand) }
            if amtW == 0 { violations.insert(.withdrawZeroAmount) }
            let key = DKey(demander: dm, amountDemanded: amtD, nonce: n)
            switch deposits[key] {
            case nil: violations.insert(.withdrawWrongAmount)
            case 0: violations.insert(.withdrawSpent)
            case let stored?: if stored != amtW || amtW == 0 { violations.insert(.withdrawWrongAmount) }
            }
            switch parent[RKey(directory: dir, demander: dm, amountDemanded: amtD, nonce: n)] {
            case nil: violations.insert(.withdrawNoReceipt)
            case let named?: if named != w { violations.insert(.withdrawWrongWithdrawer) }
            }
            deposits[key] = 0
        }
        for case let .deposit(n, dm, amtD, amt) in actions {
            let key = DKey(demander: dm, amountDemanded: amtD, nonce: n)
            if deposits[key] != nil { violations.insert(.depositExists) }
            if amt == 0 || amtD == 0 { violations.insert(.depositZero) }
            deposits[key] = amt
        }
        var receipts = state.receipts
        for case let .receipt(w, n, dm, amtD, d) in actions {
            let key = RKey(directory: d, demander: dm, amountDemanded: amtD, nonce: n)
            if receipts[key] != nil { violations.insert(.receiptExists) }
            if amtD == 0 { violations.insert(.receiptZeroDemand) }
            receipts[key] = w
        }
        if let recipient {
            deltas.append((recipient, Int64(reward) + debits + withdrawn - credits - deposited))
        }
        var balances = state.balances
        for owner in Set(deltas.map(\.0)) {
            let value = Int64(state.balances[owner] ?? 0) + deltas.filter { $0.0 == owner }.reduce(0) { $0 + $1.1 }
            if value < 0 { violations.insert(.overdraft) }
            balances[owner] = value > 0 ? UInt64(value) : nil
        }
        guard violations.isEmpty else { return (violations, nil) }
        return ([], VState(balances: balances, deposits: deposits, receipts: receipts))
    }

    static func fee(_ actions: [VAction]) -> Int64 {
        actions.reduce(0) { total, action in
            switch action {
            case let .account(_, delta): return total - delta
            case let .deposit(_, _, _, amount): return total - Int64(amount)
            case let .withdrawal(_, _, _, _, amount): return total + Int64(amount)
            case .receipt: return total
            }
        }
    }
}

// MARK: - One seeded trace

@MainActor
private final class ValueTrace {
    static let dir = "Child"
    static let chainPath = [DEFAULT_ROOT_DIRECTORY, dir]
    static let baseTimestamp: Int64 = 1_700_000_000_000

    let seed: UInt64
    var rng: SeededRNG
    let fetcher = StorableFetcher()
    let spec = ChainSpec.test(initialReward: 100)
    var keys: [String: (privateKey: String, publicKey: String)] = [:]
    let users: [String]
    let sponsor: String
    var sponsorNonce: UInt64 = 0
    /// Account actions the block carries in a second transaction (the same
    /// sponsor, the next nonce), exported after the first transaction's.
    var secondTransaction: [VAction] = []
    /// Netting shapes the current valid block was generated to show.
    var plannedFeatures: Set<String> = []

    var tip: Block
    var state = VState()
    var parentReceipts: [RKey: String] = [:]
    /// Storage key -> receipt key, for every receipt key the trace names
    /// (receipt state is keyed by a digest, spec §3.7 `storageKey`).
    var receiptPreimages: [String: RKey] = [:]

    var cases: [[String: Any]] = []
    var coverage: [String: Int] = [:]

    private init(seed: UInt64, genesis: Block, keys: [String: (String, String)], users: [String], sponsor: String) {
        self.seed = seed
        rng = SeededRNG(seed: seed &* 0x9E37_79B9)
        tip = genesis
        self.keys = keys.mapValues { (privateKey: $0.0, publicKey: $0.1) }
        self.users = users
        self.sponsor = sponsor
    }

    static func make(seed: UInt64) async throws -> ValueTrace {
        var keys: [String: (String, String)] = [:]
        func key(_ name: String) throws -> String {
            let raw = Data(SHA256.hash(data: Data("lattice-value-trace/\(seed)/\(name)".utf8)))
            let privateKey = try Curve25519.Signing.PrivateKey(rawRepresentation: raw)
            let publicKey = Multikey(keyType: .ed25519, keyBytes: privateKey.publicKey.rawRepresentation).hexEncoded
            let address = CryptoUtils.createAddress(from: publicKey)
            keys[address] = (raw.hexString, publicKey)
            return address
        }
        let users = try (0..<4).map { try key("u\($0)") }.sorted()
        let sponsor = try key("sponsor")
        let fetcher = StorableFetcher()
        let genesis = try await BlockBuilder.buildChildGenesis(
            spec: ChainSpec.test(initialReward: 100),
            parentState: LatticeState.emptyHeader,
            timestamp: baseTimestamp, target: .max, fetcher: fetcher
        )
        let trace = ValueTrace(seed: seed, genesis: genesis, keys: keys, users: users, sponsor: sponsor)
        try await storeBuiltBlock(genesis, in: trace.fetcher)
        return trace
    }

    func chance(_ numerator: Int, in denominator: Int) -> Bool {
        Int.random(in: 0..<denominator, using: &rng) < numerator
    }
    func pick<T>(_ items: [T]) -> T? { items.isEmpty ? nil : items[Int.random(in: 0..<items.count, using: &rng)] }
    func amount(_ upTo: UInt64) -> UInt64 { UInt64.random(in: 1...max(upTo, 1), using: &rng) }

    // MARK: Driving the chain

    func run() async throws {
        // Funding: coinbase-only blocks to three users.
        for index in 0..<3 {
            try await step(actions: [], recipient: users[index], violation: nil)
        }
        for _ in 0..<14 {
            evolveParentReceipts()
            let recipient = chance(1, in: 3) ? nil : pick(users)
            let valid = generateValid(recipient: recipient)
            if chance(11, in: 20) {
                try await step(actions: valid, recipient: recipient, violation: nil)
                continue
            }
            // A violation: the control first, then the block it becomes.
            let reward = spec.rewardAtBlock(tip.height + 1)
            var mutated: (Violation, [VAction])?
            for _ in 0..<40 {
                // Weighted toward the withdrawal rules, which need a live deposit.
                let withdrawalRules: [Violation] = [.withdrawWrongAmount, .withdrawNoReceipt, .withdrawWrongWithdrawer]
                guard let kind = pick(Violation.allCases + withdrawalRules + withdrawalRules),
                      let extra = violationActions(kind, base: valid, recipient: recipient) else { continue }
                let actions = valid + extra
                let verdict = ModelMirror.apply(dir: Self.dir, parent: parentReceipts, state: state,
                                                actions: actions + secondTransaction, reward: reward, recipient: recipient)
                if kind.labels(verdict.violations) { mutated = (kind, actions); break }
            }
            guard let (kind, actions) = mutated else {
                try await step(actions: valid, recipient: recipient, violation: nil)
                continue
            }
            let control = try await execute(actions: valid, recipient: recipient)
            XCTAssertTrue(control.accepted, "seed \(seed): control for \(kind) rejected: \(control.error ?? "")")
            try await step(actions: actions, recipient: recipient, violation: kind)
        }
    }

    /// Run one case through the validator, check it against the model, and
    /// record it; advance the tip when accepted.
    func step(actions unordered: [VAction], recipient: String?, violation: Violation?) async throws {
        let actions = Self.applicationOrder(unordered) + secondTransaction
        let reward = spec.rewardAtBlock(tip.height + 1)
        let expected = ModelMirror.apply(dir: Self.dir, parent: parentReceipts, state: state,
                                         actions: actions, reward: reward, recipient: recipient)
        if let violation {
            XCTAssertTrue(violation.labels(expected.violations), "seed \(seed): generator labelled the case wrongly")
        } else {
            XCTAssertEqual(expected.violations, [], "seed \(seed): generator labelled the case wrongly")
        }
        let outcome = try await execute(actions: unordered, recipient: recipient)
        if violation == nil {
            XCTAssertTrue(outcome.accepted, "seed \(seed) h\(tip.height + 1): valid block rejected: \(outcome.error ?? "")")
        } else {
            XCTAssertFalse(outcome.accepted, "seed \(seed) h\(tip.height + 1): \(violation!) accepted")
            if let violation, violation.isShapeRule {
                // Refused by the shape rule itself: the body fails it, and the
                // block is refused at transaction validation (a false verdict),
                // not by a deposit or receipt proof (which throws).
                let shaped = body(actions)
                XCTAssertFalse(violation == .receiptZeroDemand
                               ? shaped.receiptActionsAreValid() : shaped.withdrawalActionsAreValid())
                XCTAssertEqual(outcome.error, "validateNexus returned false",
                               "seed \(seed): \(violation) refused for another reason")
            }
        }
        if outcome.accepted, let post = outcome.post {
            XCTAssertEqual(post, expected.post, "seed \(seed) h\(tip.height + 1): post-state differs from the model")
        }
        cases.append([
            "dir": Self.dir,
            "parentReceipts": parentReceipts.keys.sorted().map { [receiptKeyJSON($0), parentReceipts[$0]!] },
            "prev": stateJSON(state),
            "block": [
                "actions": actions.map(actionJSON),
                "reward": Int(reward),
                "recipient": recipient as Any? ?? NSNull(),
            ] as [String: Any],
            "result": outcome.post.map(stateJSON) as Any? ?? NSNull(),
            "violates": violation?.rawValue as Any? ?? NSNull(),
        ])
        if let violation {
            coverage[violation.rawValue, default: 0] += 1
        } else if let post = outcome.post {
            recordValidFeatures(actions: actions, recipient: recipient, post: post)
        }
        if outcome.accepted, let block = outcome.block, let post = outcome.post {
            tip = block
            state = post
            sponsorNonce += UInt64(transactionCount(unordered))
        }
    }

    func recordValidFeatures(actions: [VAction], recipient: String?, post: VState) {
        func mark(_ feature: String) { coverage["valid:" + feature, default: 0] += 1 }
        // Applying the balance deltas one at a time in exported order (the
        // coinbase last) overdraws some owner: valid only under netting.
        var running = state.balances.mapValues { Int64($0) }
        var sequentialFails = false
        func apply(_ owner: String, _ delta: Int64) {
            running[owner, default: 0] += delta
            if running[owner]! < 0 { sequentialFails = true }
        }
        for action in actions {
            if case let .account(owner, delta) = action { apply(owner, delta) }
            if case let .receipt(w, _, dm, amount, _) = action { apply(w, -Int64(amount)); apply(dm, Int64(amount)) }
        }
        if let recipient { apply(recipient, Int64(spec.rewardAtBlock(tip.height + 1)) + ModelMirror.fee(actions)) }
        if sequentialFails { mark("sequentialFails") }
        // A planned shape counts only when the block really needs netting.
        if sequentialFails { plannedFeatures.sorted().forEach(mark) }
        mark(recipient == nil ? "burn" : "recipient")
        var debited: [String: UInt64] = [:], credited = Set<String>()
        for case let .account(owner, delta) in actions {
            if delta < 0 { debited[owner, default: 0] += UInt64(-delta) } else { credited.insert(owner) }
        }
        if let recipient { credited.insert(recipient) }
        if debited.keys.contains(where: credited.contains) { mark("netting") }
        if debited.contains(where: { $0.value > state.balances[$0.key] ?? 0 }) { mark("nettedOverspend") }
        if state.balances.keys.contains(where: { post.balances[$0] == nil }) { mark("zeroDeleted") }
        if post.deposits.values.contains(0) && !state.deposits.values.contains(0) { mark("spentMarker") }
        for action in actions {
            switch action {
            case .withdrawal: mark("withdrawal")
            case .receipt: mark("receipt")
            case .deposit: mark("deposit")
            case .account: break
            }
        }
    }

    // MARK: Generation

    func generateValid(recipient: String?) -> [VAction] {
        secondTransaction = []
        plannedFeatures = []
        var actions: [VAction] = []
        var available = state.balances
        var usedDeposits = Set<DKey>(), usedReceipts = Set<RKey>()
        func funded() -> String? { pick(users.filter { (available[$0] ?? 0) > 0 }) }
        for _ in 0..<Int.random(in: 1...4, using: &rng) {
            switch Int.random(in: 0..<11, using: &rng) {
            case 8, 9: // debit before credit: the debit alone exceeds the balance
                guard let source = funded(),
                      let owner = pick(users.filter { $0 != source && available[$0] == state.balances[$0] })
                else { continue }
                let covered = amount(min(available[source]!, 20))
                available[source]! -= covered
                let spent = (available[owner] ?? 0) + covered
                available[owner] = 0
                let spend: [VAction] = [.account(owner: owner, delta: -Int64(spent)),
                                        .account(owner: pick(users)!, delta: Int64(spent))]
                let cover: [VAction] = [.account(owner: source, delta: -Int64(covered)),
                                        .account(owner: owner, delta: Int64(covered))]
                if Int.random(in: 0..<2, using: &rng) == 0 || !secondTransaction.isEmpty {
                    actions = spend + cover + actions
                    plannedFeatures.insert("nettingDebitFirst")
                } else {
                    actions = spend + actions
                    secondTransaction = cover
                    plannedFeatures.insert("nettingDebitFirstTwoTx")
                }
            case 10: // the recipient overspends, covered only by its coinbase
                guard let recipient, available[recipient] == state.balances[recipient],
                      !plannedFeatures.contains("nettingCoinbase") else { continue }
                let spent = (available[recipient] ?? 0) + amount(spec.rewardAtBlock(tip.height + 1))
                available[recipient] = 0
                actions = [.account(owner: recipient, delta: -Int64(spent)),
                           .account(owner: pick(users.filter { $0 != recipient })!, delta: Int64(spent))] + actions
                plannedFeatures.insert("nettingCoinbase")
            case 0, 1: // transfer, possibly back to the payer, possibly leaving a fee
                guard let payer = funded() else { continue }
                let paid = amount(min(available[payer]!, 40))
                available[payer]! -= paid
                actions.append(.account(owner: payer, delta: -Int64(paid)))
                let credit = UInt64.random(in: 0...paid, using: &rng)
                if credit > 0 { actions.append(.account(owner: pick(users)!, delta: Int64(credit))) }
            case 2: // drain a balance to exactly zero
                guard let payer = funded() else { continue }
                let paid = available[payer]!
                available[payer] = 0
                actions.append(.account(owner: payer, delta: -Int64(paid)))
                let payee = pick(users.filter { $0 != payer })!
                actions.append(.account(owner: payee, delta: Int64(UInt64.random(in: 1...paid, using: &rng))))
            case 3: // spend more than the balance, covered by a credit in the same block
                guard let source = funded(), let through = pick(users.filter { $0 != source }) else { continue }
                let relayed = amount(min(available[source]!, 20))
                available[source]! -= relayed
                let spent = (available[through] ?? 0) + relayed
                available[through] = 0
                actions.append(.account(owner: source, delta: -Int64(relayed)))
                actions.append(.account(owner: through, delta: Int64(relayed)))
                actions.append(.account(owner: through, delta: -Int64(spent)))
                actions.append(.account(owner: pick(users)!, delta: Int64(spent)))
            case 4, 7: // deposit, funded by the demander
                guard let demander = funded() else { continue }
                let key = DKey(demander: demander, amountDemanded: amount(50), nonce: UInt64.random(in: 0...3, using: &rng))
                guard state.deposits[key] == nil, usedDeposits.insert(key).inserted else { continue }
                let locked = amount(min(available[demander]!, 30))
                available[demander]! -= locked
                actions.append(.account(owner: demander, delta: -Int64(locked)))
                actions.append(.deposit(nonce: key.nonce, demander: demander, amountDemanded: key.amountDemanded, amountDeposited: locked))
            case 5: // withdrawal of a live deposit the parent has a receipt for
                let ready = state.deposits.keys.sorted().filter {
                    state.deposits[$0]! > 0 && !usedDeposits.contains($0) && parentReceipts[receiptKey(for: $0)] != nil
                }
                guard let key = pick(ready) else { continue }
                usedDeposits.insert(key)
                let withdrawer = parentReceipts[receiptKey(for: key)]!
                let value = state.deposits[key]!
                actions.append(.withdrawal(withdrawer: withdrawer, nonce: key.nonce, demander: key.demander,
                                           amountDemanded: key.amountDemanded, amountWithdrawn: value))
                let credit = UInt64.random(in: 0...value, using: &rng)
                if credit > 0 { actions.append(.account(owner: withdrawer, delta: Int64(credit))) }
            default: // receipt for a grandchild's deposit
                guard let withdrawer = funded() else { continue }
                let key = RKey(directory: pick(["G1", "G2"])!, demander: pick(users)!,
                               amountDemanded: amount(min(available[withdrawer]!, 30)),
                               nonce: UInt64.random(in: 0...3, using: &rng))
                guard state.receipts[key] == nil, usedReceipts.insert(key).inserted else { continue }
                available[withdrawer]! -= key.amountDemanded
                actions.append(.receipt(withdrawer: withdrawer, nonce: key.nonce, demander: key.demander,
                                        amountDemanded: key.amountDemanded, directory: key.directory))
            }
        }
        return actions
    }

    /// Actions that, added to `base`, break `kind` (the caller keeps them only
    /// when the model says they break exactly that rule).
    func violationActions(_ kind: Violation, base: [VAction], recipient: String?) -> [VAction]? {
        let deposits = state.deposits.keys.sorted()
        func withdraw(_ key: DKey, by withdrawer: String, _ amount: UInt64) -> VAction {
            .withdrawal(withdrawer: withdrawer, nonce: key.nonce, demander: key.demander,
                        amountDemanded: key.amountDemanded, amountWithdrawn: amount)
        }
        func funding(_ amount: UInt64) -> [VAction] {
            guard let payer = pick(users) else { return [] }
            return [.account(owner: payer, delta: -Int64(amount))]
        }
        switch kind {
        case .overdraft:
            guard let owner = pick(users.filter { $0 != recipient }) else { return nil }
            let after = ModelMirror.apply(dir: Self.dir, parent: parentReceipts, state: state,
                                          actions: base + secondTransaction, reward: 0, recipient: nil).post?.balances[owner] ?? 0
            return [.account(owner: owner, delta: -Int64(after + amount(5)))]
        case .feeRule:
            return [.account(owner: pick(users)!, delta: max(ModelMirror.fee(base), 0) + Int64(amount(5)))]
        case .deltaZero:
            return [.account(owner: pick(users)!, delta: 0)]
        case .depositExists:
            guard let key = pick(deposits) else { return nil }
            let locked = amount(10)
            return funding(locked) + [.deposit(nonce: key.nonce, demander: key.demander,
                                               amountDemanded: key.amountDemanded, amountDeposited: locked)]
        case .depositZero:
            let nonce = UInt64.random(in: 10...20, using: &rng)
            if chance(1, in: 2) {
                return [.deposit(nonce: nonce, demander: pick(users)!, amountDemanded: amount(50), amountDeposited: 0)]
            }
            let locked = amount(10)
            return funding(locked) + [.deposit(nonce: nonce, demander: pick(users)!, amountDemanded: 0, amountDeposited: locked)]
        case .withdrawWrongAmount:
            guard let key = pick(deposits.filter { state.deposits[$0]! > 0 && parentReceipts[receiptKey(for: $0)] != nil })
            else { return nil }
            let value = state.deposits[key]!
            let wrong = chance(1, in: 2) || value == 1 ? value + amount(5) : value - amount(value - 1)
            return [withdraw(key, by: parentReceipts[receiptKey(for: key)]!, wrong)]
        case .withdrawNoReceipt:
            guard let key = pick(deposits.filter { state.deposits[$0]! > 0 && parentReceipts[receiptKey(for: $0)] == nil })
            else { return nil }
            return [withdraw(key, by: pick(users)!, state.deposits[key]!)]
        case .withdrawWrongWithdrawer:
            guard let key = pick(deposits.filter { state.deposits[$0]! > 0 && parentReceipts[receiptKey(for: $0)] != nil })
            else { return nil }
            let named = parentReceipts[receiptKey(for: key)]!
            return [withdraw(key, by: pick(users.filter { $0 != named })!, state.deposits[key]!)]
        case .withdrawSpent:
            guard let key = pick(deposits.filter { state.deposits[$0]! == 0 && parentReceipts[receiptKey(for: $0)] != nil })
            else { return nil }
            return [withdraw(key, by: parentReceipts[receiptKey(for: key)]!, amount(50))]
        case .receiptZeroDemand:
            let key = RKey(directory: pick(["G1", "G2"])!, demander: pick(users)!, amountDemanded: 0,
                           nonce: UInt64.random(in: 0...3, using: &rng))
            guard state.receipts[key] == nil else { return nil }
            return [.receipt(withdrawer: pick(users)!, nonce: key.nonce, demander: key.demander,
                             amountDemanded: 0, directory: key.directory)]
        case .withdrawZeroDemand:
            return [.withdrawal(withdrawer: pick(users)!, nonce: UInt64.random(in: 0...3, using: &rng),
                                demander: pick(users)!, amountDemanded: 0, amountWithdrawn: amount(50))]
        case .withdrawZeroAmount:
            guard let key = pick(deposits.filter { state.deposits[$0]! > 0 && parentReceipts[receiptKey(for: $0)] != nil })
            else { return nil }
            return [withdraw(key, by: parentReceipts[receiptKey(for: key)]!, 0)]
        case .receiptExists:
            guard let key = pick(state.receipts.keys.sorted()) else { return nil }
            return [.receipt(withdrawer: pick(users)!, nonce: key.nonce, demander: key.demander,
                             amountDemanded: key.amountDemanded, directory: key.directory)]
        }
    }

    func receiptKey(for deposit: DKey) -> RKey {
        RKey(directory: Self.dir, demander: deposit.demander, amountDemanded: deposit.amountDemanded, nonce: deposit.nonce)
    }

    /// The parent chain moves on: a receipt for some live deposit lands (not
    /// every deposit gets one), and now and then an unrelated receipt.
    func evolveParentReceipts() {
        let pending = state.deposits.keys.sorted().filter {
            state.deposits[$0]! > 0 && parentReceipts[receiptKey(for: $0)] == nil
        }
        if chance(3, in: 5), let key = pick(pending) {
            parentReceipts[receiptKey(for: key)] = pick(users)!
        }
        if chance(1, in: 5) {
            let key = RKey(directory: pick([Self.dir, "Other"])!, demander: pick(users)!,
                           amountDemanded: amount(50), nonce: UInt64.random(in: 0...3, using: &rng))
            if parentReceipts[key] == nil, state.deposits[key.deposit] == nil || key.directory != Self.dir {
                parentReceipts[key] = pick(users)!
            }
        }
    }

    // MARK: The validator

    struct Outcome {
        let accepted: Bool
        let block: Block?
        let post: VState?
        let error: String?
    }

    /// The order the validator applies the kinds in: withdrawals spend before
    /// deposits insert (§6.4); receipts and account actions follow. Each kind
    /// keeps its body order (account actions net per owner, so theirs is moot).
    static func applicationOrder(_ actions: [VAction]) -> [VAction] {
        func rank(_ action: VAction) -> Int {
            switch action {
            case .withdrawal: return 0
            case .deposit: return 1
            case .receipt: return 2
            case .account: return 3
            }
        }
        return actions.enumerated().sorted { (rank($0.element), $0.offset) < (rank($1.element), $1.offset) }.map(\.element)
    }

    func execute(actions unordered: [VAction], recipient: String?) async throws -> Outcome {
        let actions = Self.applicationOrder(unordered)
        let height = tip.height + 1
        let timestamp = Self.baseTimestamp + Int64(height) * 1_000
        var transactions: [Transaction] = []
        if !actions.isEmpty { transactions.append(sign(body(actions, nonce: sponsorNonce))) }
        if !secondTransaction.isEmpty {
            transactions.append(sign(body(secondTransaction, nonce: sponsorNonce + UInt64(transactions.count))))
        }

        let parentState = try await parentStateHeader()
        let built: Block
        do {
            built = try await BlockBuilder.buildBlockWithTransition(
                previous: tip, transactions: transactions, timestamp: timestamp,
                target: .max, rewardRecipient: recipient, fetcher: fetcher
            ).block
        } catch {
            // The builder refuses what the transition or coinbase refuses;
            // such a block declares its prevState as its postState, which the
            // validator never reaches.
            let header = try await BlockBuilder.buildBlockWithTransition(
                previous: tip, timestamp: timestamp, target: .max,
                rewardRecipient: recipient, fetcher: fetcher
            ).block
            built = Block(
                version: header.version, parent: header.parent,
                transactions: try BlockBuilder.buildTransactionsDictionary(transactions),
                target: header.target, nextTarget: header.nextTarget, spec: header.spec,
                parentState: header.parentState, prevState: header.prevState,
                postState: header.prevState, children: header.children,
                height: header.height, timestamp: header.timestamp,
                rewardRecipient: recipient, nonce: header.nonce
            )
        }
        let block = Block(
            version: built.version, parent: built.parent, transactions: built.transactions,
            target: built.target, nextTarget: built.nextTarget, spec: built.spec,
            parentState: parentState, prevState: built.prevState, postState: built.postState,
            children: built.children, height: built.height, timestamp: built.timestamp,
            rewardRecipient: built.rewardRecipient, nonce: built.nonce
        )
        try await storeBuiltBlock(block, in: fetcher)

        let verdict: (Bool, StateDiff, LatticeState?)
        do {
            verdict = try await block.validateNexus(fetcher: fetcher, chainPath: Self.chainPath)
        } catch {
            return Outcome(accepted: false, block: nil, post: nil, error: String(describing: error))
        }
        guard verdict.0, let post = verdict.2 else {
            return Outcome(accepted: false, block: nil, post: nil, error: "validateNexus returned false")
        }
        return Outcome(accepted: true, block: block, post: try await readBack(post), error: nil)
    }

    func transactionCount(_ actions: [VAction]) -> Int {
        (actions.isEmpty ? 0 : 1) + (secondTransaction.isEmpty ? 0 : 1)
    }

    func body(_ actions: [VAction], nonce: UInt64 = 0) -> TransactionBody {
        var accounts: [AccountAction] = [], deposits: [DepositAction] = []
        var receipts: [ReceiptAction] = [], withdrawals: [WithdrawalAction] = []
        var signers = Set<String>()
        for action in actions {
            switch action {
            case let .account(owner, delta):
                accounts.append(AccountAction(owner: owner, delta: delta))
                if delta < 0 { signers.insert(owner) }
            case let .deposit(n, dm, amtD, amt):
                deposits.append(DepositAction(nonce: UInt128(n), demander: dm, amountDemanded: amtD, amountDeposited: amt))
                signers.insert(dm)
            case let .withdrawal(w, n, dm, amtD, amt):
                withdrawals.append(WithdrawalAction(withdrawer: w, nonce: UInt128(n), demander: dm,
                                                    amountDemanded: amtD, amountWithdrawn: amt))
                signers.insert(w)
            case let .receipt(w, n, dm, amtD, d):
                receipts.append(ReceiptAction(withdrawer: w, nonce: UInt128(n), demander: dm, amountDemanded: amtD, directory: d))
                signers.insert(w)
                receiptPreimages[RKey(directory: d, demander: dm, amountDemanded: amtD, nonce: n).storageKey] =
                    RKey(directory: d, demander: dm, amountDemanded: amtD, nonce: n)
            }
        }
        return TransactionBody(
            accountActions: accounts, actions: [], depositActions: deposits,
            receiptActions: receipts, withdrawalActions: withdrawals,
            signers: [sponsor] + signers.subtracting([sponsor]).sorted(),
            nonce: nonce, chainPath: Self.chainPath
        )
    }

    func sign(_ body: TransactionBody) -> Transaction {
        let header = try! HeaderImpl<TransactionBody>(node: body)
        var signatures: [String: String] = [:]
        for signer in body.signers {
            let key = keys[signer]!
            signatures[key.publicKey] = TransactionSigning.sign(bodyHeader: header, privateKeyHex: key.privateKey)!
        }
        return Transaction(signatures: signatures, body: header)
    }

    /// A parent state whose receipt state holds exactly `parentReceipts`,
    /// built by the receipt-state transition itself.
    func parentStateHeader() async throws -> LatticeStateHeader {
        let actions = parentReceipts.keys.sorted().map { key in
            ReceiptAction(withdrawer: parentReceipts[key]!, nonce: UInt128(key.nonce), demander: key.demander,
                          amountDemanded: key.amountDemanded, directory: key.directory)
        }
        let (receiptState, _) = try await LatticeState.empty.receiptState.proveAndUpdateState(
            allReceiptActions: actions, fetcher: fetcher
        )
        let empty = LatticeState.empty
        let header = try LatticeStateHeader(node: LatticeState(
            accountState: empty.accountState, generalState: empty.generalState,
            depositState: empty.depositState, receiptState: receiptState
        ))
        try await header.storeRecursively(storer: fetcher)
        return header
    }

    /// Every entry of the three value sub-states, as the validator left them.
    func readBack(_ post: LatticeState) async throws -> VState {
        var result = VState()
        let accounts = try await post.accountState.resolveRecursive(fetcher: fetcher)
        for (key, value) in try accounts.node?.allKeysAndValues() ?? [:]
        where !AccountStateHeader.isReservedAccountKey(key) {
            result.balances[key] = value
        }
        let deposits = try await post.depositState.resolveRecursive(fetcher: fetcher)
        for (key, value) in try deposits.node?.allKeysAndValues() ?? [:] {
            let parsed = try XCTUnwrap(DepositKey(key))
            result.deposits[DKey(demander: parsed.demander, amountDemanded: parsed.amountDemanded,
                                 nonce: UInt64(parsed.nonce))] = value
        }
        let receipts = try await post.receiptState.resolveRecursive(fetcher: fetcher)
        for (key, value) in try receipts.node?.allKeysAndValues() ?? [:] {
            result.receipts[try XCTUnwrap(receiptPreimages[key], "unknown receipt storage key")] = value
        }
        return result
    }

    // MARK: JSON

    func receiptKeyJSON(_ key: RKey) -> [String: Any] {
        ["directory": key.directory, "demander": key.demander,
         "amountDemanded": Int(key.amountDemanded), "nonce": Int(key.nonce)]
    }

    func stateJSON(_ state: VState) -> [String: Any] {
        [
            "balances": state.balances.keys.sorted().map { [$0, Int(state.balances[$0]!)] as [Any] },
            "deposits": state.deposits.keys.sorted().map { key -> [Any] in
                [["demander": key.demander, "amountDemanded": Int(key.amountDemanded), "nonce": Int(key.nonce)],
                 Int(state.deposits[key]!)]
            },
            "receipts": state.receipts.keys.sorted().map { [receiptKeyJSON($0), state.receipts[$0]!] as [Any] },
        ]
    }

    func actionJSON(_ action: VAction) -> [String: Any] {
        switch action {
        case let .account(owner, delta):
            return ["kind": "account", "owner": owner, "delta": Int(delta)]
        case let .deposit(n, dm, amtD, amt):
            return ["kind": "deposit", "nonce": Int(n), "demander": dm,
                    "amountDemanded": Int(amtD), "amountDeposited": Int(amt)]
        case let .withdrawal(w, n, dm, amtD, amt):
            return ["kind": "withdrawal", "withdrawer": w, "nonce": Int(n), "demander": dm,
                    "amountDemanded": Int(amtD), "amountWithdrawn": Int(amt)]
        case let .receipt(w, n, dm, amtD, d):
            return ["kind": "receipt", "withdrawer": w, "nonce": Int(n), "demander": dm,
                    "amountDemanded": Int(amtD), "directory": d]
        }
    }

    func json() throws -> Data {
        try JSONSerialization.data(withJSONObject: cases, options: [.prettyPrinted, .sortedKeys])
    }
